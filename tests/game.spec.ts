import { expect, test } from '@playwright/test'

test('resolve a docket from real spikes, view the press briefing and restore the mandate', async ({page}) => {
  await page.goto('/')
  await expect(page.getByRole('heading', {name:'Señor Mosca'})).toBeVisible()
  await page.getByRole('button', {name:'Cómo jugar'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', {name:'Volver al cabildo'}).click()
  await page.getByRole('button', {name:'Un hotel para la duna'}).click()
  await page.getByLabel('Énfasis del informe').selectOption('citizens')
  await page.getByRole('button', {name:'Presentar expediente'}).click()
  await expect(page.getByRole('heading', {name:'Salvar el acceso público'})).toBeVisible()
  await expect(page.getByText('Día 2 / 10')).toBeVisible()
  await expect(page.getByText('300 / 300 ms')).toBeVisible()
  await expect(page.getByRole('img', {name:/Raster de 18 neuronas.*[1-9][0-9]* disparos/})).toBeVisible()
  await expect(page.getByText('Si la playa no tiene puerta', {exact:false})).toBeVisible()
  await page.reload()
  await expect(page.getByText('Día 2 / 10')).toBeVisible()
  await page.getByText('Ver bitácora (1)').click()
  await expect(page.getByText('Día 1 · Un hotel para la duna')).toBeVisible()
  await page.getByRole('button', {name:'Reiniciar mandato'}).click()
  await expect(page.getByText('Día 1 / 10')).toBeVisible()
})

test('mobile can play a case with no horizontal scrolling', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await page.getByRole('button', {name:'Presentar expediente'}).click()
  await expect(page.getByRole('heading', {name:'Pipas para las colonias'})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('optional whole-brain turn streams v783 activity and uses the early score', async ({page}) => {
  test.skip(process.env.MOSCA_TEST_FULL !== '1', 'Requires pinned FlyWire v783 tables')
  test.setTimeout(90_000)
  await page.goto('/')
  await page.getByLabel('Modo neural').selectOption('flywire')
  await page.getByRole('button', {name:'Presentar expediente'}).click()
  await expect(page.getByText('30 / 300 ms', {exact:true})).toBeVisible({timeout:30_000})
  await expect(page.getByText('La decisión usa los primeros 30 ms', {exact:false})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Pipas para las colonias'})).toBeVisible({timeout:60_000})
  await expect(page.getByText('138,639 neuronas activas', {exact:false})).toBeVisible()
  await expect(page.getByText('Día 2 / 10')).toBeVisible()
})
